const weekly = (
  days: number[],
  startTime: string,
  endTime: string,
  repeat: 'weekly' | 'fortnightly' = 'weekly',
): ActivitySchedule => ({
  repeat,
  date: '2026-01-04',
  until: '',
  days,
  monthWeek: 1,
  monthDay: 0,
  startTime,
  endTime,
});
const monthly = (
  monthWeek: number,
  monthDay: number,
  startTime: string,
  endTime: string,
): ActivitySchedule => ({
  ...weekly([], startTime, endTime),
  repeat: 'monthly',
  monthWeek,
  monthDay,
});
const once = (
  date: string,
  startTime: string,
  endTime: string,
): ActivitySchedule => ({
  ...weekly([], startTime, endTime),
  repeat: 'once',
  date,
});
